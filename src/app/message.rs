//! Everything that can happen to the player.

use crate::model::Entry;
use enzui_core::portal::PortalOutcome;
use enzui_core::theme_file::integration::ThemeEvent;
use enzui_widgets::file_chooser::FileResult;
use enzui_widgets::form_dialog::FormDialogEvent;
use enzui_widgets::menu_button::MenuButtonEvent;
use enzui_widgets::toast_host::ToastEvent;
use enzui_widgets::video::ReadyFrame;
use std::path::PathBuf;
use std::time::Duration;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Pick {
    Videos,
    Queue,
    Subtitles,
}

#[derive(Debug, Clone)]
pub(crate) enum Message {
    Plex(crate::plex::Event),
    Theme(Box<ThemeEvent>),
    VideoWake,
    TimelineFrame,
    RetryMedia(u64),
    FrameReady(ReadyFrame),

    TogglePlay,
    SurfacePress,
    SurfaceClick(u64),
    Backspace,
    // Jump to a position, accurately.
    SeekTo(Duration),
    // The scrubber moved to this many seconds.
    Scrub(f32),
    ScrubStarted,
    ScrubReleased,
    // Request an accurate seek only if no newer scrub superseded `token`.
    ScrubSettled(u64),
    // Move by this many milliseconds, back when negative.
    SkipBy(i64),
    // Seek to this fraction of the duration (the 0–9 keys).
    SeekFraction(f32),
    StepFrame(bool),
    SetVolume(f64),
    VolumeBy(f64),
    ToggleMute,
    RateStep(bool),
    Next,
    Previous,
    CycleRepeat,
    PlayIndex(usize),
    RemoveFromQueue(usize),
    QueueDropped(Option<Entry>, enzui_widgets::file_drop::DataDrop),
    CycleSubtitles,
    CycleAudio,
    // Shift subtitles by this many milliseconds; zero puts them back in
    // sync.
    SubtitleDelay(i64),

    SubtitlesMenu(MenuButtonEvent),
    AudioMenu(MenuButtonEvent),
    SpeedMenu(MenuButtonEvent),
    TitlebarMenu(bool),
    QueueContext(Entry, iced::Point),
    QueueMenu(enzui_widgets::context_menu_host::ContextMenuEvent),
    ToggleTitlebarMenu,
    AccountMenu(MenuButtonEvent),
    SourceMenu(MenuButtonEvent),
    SortMenu(MenuButtonEvent),
    QualityMenu(MenuButtonEvent),

    Choose(Pick),
    ChooserWake,
    ChooserWindow(u64, Option<iced::window::Id>),
    ChooserParent(u64, super::chooser::ParentReply),
    ChooserFallback(enzui_widgets::file_chooser::FallbackEvent),
    ApplicationWake,
    MemoryPressure(enzui_core::system_status::MemoryPressure),
    ReceiveFiles(super::native_drop::Offer),
    NativeFiles(super::NativeDelivery),
    Sleep(enzui_core::system_sleep::SleepEvent),
    Session(enzui_core::portal::session_monitor::SessionEvent),
    Chosen(Pick, PortalOutcome<FileResult>),
    OpenUrlDialog,
    UrlForm(FormDialogEvent),
    OpenRecent(usize),
    ForgetRecent(usize),
    ClearRecent,
    Dropped(Vec<PathBuf>),
    Launched(Vec<std::ffi::OsString>),
    // Resolved desktop inputs; drop order survives asynchronous disk completion.
    DropResolved {
        token: u64,
        order: Option<usize>,
        videos: Vec<Entry>,
        subtitle: Option<PathBuf>,
    },
    SiblingSubtitle(u64, Option<PathBuf>),

    Activity,
    PointerOverControls(bool),
    HideChrome,
    ToggleFullscreen,
    ExitFullscreenOrClose,
    Resized(iced::Size),
    Rescaled(f32),
    TogglePlaylist,
    QueueNavigation(enzui_widgets::nav_split::NavSplitState),
    ShowInfo,
    ShowShortcuts,
    CloseDialog,
    DialogEvent(enzui_widgets::modal_host::DialogEvent<super::Dialog>),
    SaveFrame,
    FrameSaved(Result<PathBuf, String>),
    Saved(Result<(), String>),
    ThumbnailsLoaded(Vec<(String, crate::model::thumbnail::Thumbnail)>),
    OsdExpired(u64),
    Toast(ToastEvent),

    CloseWindow,
    Window(enzui_widgets::title_bar_gesture::WindowCommand),
    CloseRequested(iced::window::Id),
    Flushed(iced::window::Id),
}

